namespace DubUrl.Querying.Dialects;

/// <summary>Reusable SQL syntax selected by provider-owned capabilities.</summary>
/// <remarks>Providers can override individual operations without copying shared schema templates.</remarks>
public class StandardSchemaSqlRenderer : ISchemaSqlRenderer
{
    public static StandardSchemaSqlRenderer Instance { get; } = new();

    public virtual string RenderCreateIndexName(IDialect dialect, SchemaSqlObjectName index, SchemaSqlObjectName table)
        => RenderObjectName(dialect, index.Catalog, index.Database, index.Schema, index.Name);

    public virtual bool RenderForeignKeysInline(IDialect dialect)
        => (dialect.Capabilities ?? DialectCapabilities.Default).IdentityColumns == IdentityColumnSyntax.SqliteTableConstraint;

    public virtual string RenderIdentity(IDialect dialect, string type, long seed, long increment)
        => (dialect.Capabilities ?? DialectCapabilities.Default).IdentityColumns switch
        {
            IdentityColumnSyntax.SqlServer => $"{type} IDENTITY({seed}, {increment})",
            IdentityColumnSyntax.PostgreSql =>
                $"{type} GENERATED BY DEFAULT AS IDENTITY (START WITH {seed} INCREMENT BY {increment})",
            IdentityColumnSyntax.MySql when seed == 1 && increment == 1 =>
                $"{type} AUTO_INCREMENT",
            IdentityColumnSyntax.MySql => throw new NotSupportedException(
                $"Dialect '{dialect.GetType().Name}' cannot represent per-column identity seed or increment values."),
            IdentityColumnSyntax.SqliteTableConstraint => throw new NotSupportedException(
                "SQLite auto-increment requires the table-specific INTEGER PRIMARY KEY AUTOINCREMENT form and cannot represent a provider-neutral identity column."),
            _ => throw new NotSupportedException(
                $"Identity columns are not supported by dialect '{dialect.GetType().Name}'.")
        };

    public virtual string RenderGenerated(IDialect dialect, string type, string expression, bool stored)
    {
        return (dialect.Capabilities ?? DialectCapabilities.Default).GeneratedColumns switch
        {
            GeneratedColumnSyntax.SqlServer => $"AS ({expression}){(stored ? " PERSISTED" : string.Empty)}",
            GeneratedColumnSyntax.PostgreSql when stored =>
                $"{type} GENERATED ALWAYS AS ({expression}) STORED",
            GeneratedColumnSyntax.PostgreSql => throw new NotSupportedException(
                "PostgreSQL does not support virtual generated columns."),
            GeneratedColumnSyntax.CockroachDb when stored =>
                $"{type} AS ({expression}) STORED",
            GeneratedColumnSyntax.CockroachDb => throw new NotSupportedException(
                "CockroachDB does not support virtual generated columns."),
            GeneratedColumnSyntax.MySql =>
                $"{type} GENERATED ALWAYS AS ({expression}) {(stored ? "STORED" : "VIRTUAL")}",
            GeneratedColumnSyntax.DuckDb when !stored =>
                $"{type} GENERATED ALWAYS AS ({expression}) VIRTUAL",
            GeneratedColumnSyntax.DuckDb => throw new NotSupportedException(
                "DuckDB does not support stored generated columns."),
            _ => throw new NotSupportedException(
                $"Generated columns are not supported by dialect '{dialect.GetType().Name}'.")
        };
    }

    public virtual string RenderRegex(IDialect dialect, string expression, string pattern)
    {
        return (dialect.Capabilities ?? DialectCapabilities.Default).RegularExpressions switch
        {
            RegularExpressionSyntax.TildeOperator => $"{expression} ~ {pattern}",
            RegularExpressionSyntax.RegexpOperator => $"{expression} REGEXP {pattern}",
            RegularExpressionSyntax.RegexpMatchesFunction => $"regexp_matches({expression}, {pattern})",
            _ => throw new NotSupportedException(
                $"Regular-expression checks are not supported by dialect '{dialect.GetType().Name}'.")
        };
    }

    public virtual string RenderObjectName(IDialect dialect, string? catalog, string? database, string? schema, string name)
    {
        var components = (dialect.Capabilities ?? DialectCapabilities.Default).ObjectNames switch
        {
            ObjectNameQualification.FourPart => new[] { catalog, database, schema, name },
            ObjectNameQualification.PostgreSql => PostgreSqlComponents(catalog, database, schema, name, dialect),
            ObjectNameQualification.MySql => MySqlComponents(catalog, database, schema, name, dialect),
            ObjectNameQualification.DuckDb => DuckDbComponents(catalog, database, schema, name, dialect),
            ObjectNameQualification.Sqlite => SqliteComponents(catalog, database, schema, name, dialect),
            _ => AnsiComponents(catalog, database, schema, name, dialect)
        };

        return string.Join('.', components.Where(component => component is not null)
            .Select(component => dialect.Renderer.Render(component, "identity")));
    }

    private static string?[] PostgreSqlComponents(string? catalog, string? database, string? schema, string name, IDialect dialect)
    {
        Reject(catalog, "Catalog", dialect);
        Reject(database, "Database", dialect);
        return [schema, name];
    }

    private static string?[] MySqlComponents(string? catalog, string? database, string? schema, string name, IDialect dialect)
    {
        Reject(catalog, "Catalog", dialect);
        Reject(schema, "Schema", dialect);
        return [database, name];
    }

    private static string?[] DuckDbComponents(string? catalog, string? database, string? schema, string name, IDialect dialect)
    {
        Reject(catalog, "Catalog", dialect);
        return [database, schema, name];
    }

    private static string?[] SqliteComponents(string? catalog, string? database, string? schema, string name, IDialect dialect)
    {
        Reject(catalog, "Catalog", dialect);
        Reject(schema, "Schema", dialect);
        return [database, name];
    }

    private static string?[] AnsiComponents(string? catalog, string? database, string? schema, string name, IDialect dialect)
    {
        Reject(catalog, "Catalog", dialect);
        Reject(database, "Database", dialect);
        return [schema, name];
    }

    private static void Reject(string? component, string componentName, IDialect dialect)
    {
        if (component is not null)
            throw new NotSupportedException(
                $"Qualifier '{componentName}' is not supported by dialect '{dialect.GetType().Name}'.");
    }
}
